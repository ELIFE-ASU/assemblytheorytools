def compose_all(
    graphs: List[nx.Graph], attribute: str = "level", get_atomic_count: bool = True
) -> nx.MultiDiGraph:
    """
    Compose multiple NetworkX graphs into a single unified graph with accumulated statistics.

    This function merges a collection of NetworkX graphs into one composite graph while
    preserving and accumulating node/edge data across all input graphs. It computes
    various statistical measures including occurrence counts, usage patterns, and
    atomic distributions.

    Parameters
    ----------
    graphs : list of networkx.Graph
        Collection of NetworkX graphs to compose. All graphs
        must be of the same type (all graphs or all multigraphs).
        Empty list will raise ValueError.
    attribute : str, optional
        Node attribute name to use for data accumulation and
        level-based analysis, by default "level".
    get_atomic_count : bool, optional
        If True, computes atomic distribution statistics
        for nodes. Useful for molecular graphs, by default True.

    Returns
    -------
    networkx.MultiDiGraph
        Unified graph containing all nodes and edges from the input graphs,
        with these additional computed attributes:

        - Node attributes -- ``attribute`` holds the values accumulated from the
          input graphs, ``"count"`` the number of times each node appears across
          graphs, ``"usage"`` the usage statistics based on ``attribute``, and
          ``"atomic_count"`` the atomic distribution when ``get_atomic_count``
          is True.
        - Edge attributes -- ``"count"`` holds the number of times each edge
          appears across graphs.
        - Graph attributes -- merged from all input graphs, with later graphs
          taking precedence.


    Raises
    ------
    ValueError
        If an empty list of graphs is provided.
    networkx.NetworkXError
        If graphs are not all of the same type (graph vs multigraph).
    """

    result = None
    updated_nodes_data, node_counts = accumulate_nodes_data(graphs, attribute=attribute)
    updated_edges_data = accumulate_edges_data(graphs)

    for graph in graphs:
        # Collapse parallel edges; their multiplicity is stored in "count".
        graph = nx.DiGraph(graph)
        if result is None:
            result = nx.DiGraph()
        result.graph.update(graph.graph)
        result.add_nodes_from(graph.nodes)
        result.add_edges_from(graph.edges)

    nx.set_node_attributes(result, values=updated_nodes_data, name=attribute)
    nx.set_node_attributes(result, values=node_counts, name="count")
    nx.set_edge_attributes(result, values=updated_edges_data, name="count")
    nx.set_node_attributes(
        result, values=accumulate_node_usage(result, attribute=attribute), name="usage"
    )

    if get_atomic_count:
        nx.set_node_attributes(result, values=get_atomic_distribution(result), name="atomic_count")

    if result is None:
        raise ValueError("cannot apply compose_all to an empty list")
    return result


def accumulate_edges_data(graphs: List[nx.Graph]) -> Dict[Tuple[Any, Any], int]:
    """
    Count edge occurrences across a collection of NetworkX graphs.

    Parameters
    ----------
    graphs : list of networkx.Graph
        Collection of NetworkX graphs to analyze.

    Returns
    -------
    dict
        Mapping from edge tuple to occurrence count. Keys are ``(node1, node2)``
        for undirected graphs or ``(source, target)`` for directed graphs, and
        values are the number of input graphs containing that edge.
    """
    edge_counts = {}
    for graph in graphs:
        for edge in graph.edges():
            edge_counts[edge] = edge_counts.get(edge, 0) + 1
    return edge_counts


def accumulate_nodes_data(
    graphs: List[nx.Graph], attribute: str = "level"
) -> Tuple[Dict[Any, Any], Dict[Any, int]]:
    """
    Accumulate node data across multiple graphs, keeping minimum attribute values and occurrence counts.

    Parameters
    ----------
    graphs : list of networkx.Graph
        Collection of NetworkX graphs to analyze.
    attribute : str, optional
        Node attribute to track minimum values for, by default "level".

    Returns
    -------
    tuple of dict
        Two dictionaries:
        - nodes_data: Maps node IDs to minimum attribute values across all graphs
        - node_counts: Maps node IDs to occurrence counts across all graphs
    """

    nodes_data = {}
    node_counts = {}

    for graph in graphs:
        for node, attributes in graph.nodes(data=True):
            if node not in nodes_data or attributes[attribute] < nodes_data[node]:
                nodes_data[node] = attributes[attribute]
            node_counts[node] = node_counts.get(node, 0) + 1

    return nodes_data, node_counts


def accumulate_node_usage(graph: nx.DiGraph, attribute: str = "usage") -> Dict[Any, List[Any]]:
    """
    Collect attribute values from the target nodes each node connects to.

    Parameters
    ----------
    graph : nx.DiGraph
        Directed graph to analyse.
    attribute : str, optional
        Node attribute to collect from the target nodes. Default is ``"usage"``.

    Returns
    -------
    dict
        Mapping from each node ID to the list of attribute values taken from its
        target nodes. Nodes with no outgoing edges map to an empty list.
    """
    return {
        node: [graph.nodes[target][attribute] for _, target in graph.out_edges(node)]
        for node in graph
    }


def get_atomic_distribution(graph: nx.Graph) -> Dict[Any, Optional[Set[int]]]:
    """
    Find the atoms with free valence in each node of a molecular graph.

    Atoms with free valence are the reactive sites available for bonding. Node
    IDs are assumed to be SMILES strings.

    Parameters
    ----------
    graph : nx.Graph
        Graph whose node IDs are SMILES strings representing molecules.

    Returns
    -------
    dict
        Mapping from each node ID to the set of atomic numbers that have
        available bonding sites, or to ``None`` if the SMILES string could not
        be parsed.
    """
    pt = Chem.rdchem.GetPeriodicTable()
    atomic_count = defaultdict(set)

    for node in graph.nodes:
        mol = MolFromSmiles(node)
        if mol is None:
            atomic_count[node] = None
            continue

        for atom in mol.GetAtoms():
            free_valence = pt.GetDefaultValence(atom.GetSymbol()) - atom.GetExplicitValence()
            if free_valence > 0:
                atomic_count[node].add(atom.GetAtomicNum())

    return atomic_count


def destringyfy(string: str) -> Any:
    """
    Safely parse a string representation of a Python literal.

    Parameters
    ----------
    string : str
        String representation of a Python literal.

    Returns
    -------
    Any
        The parsed Python object, such as a list, dict, int, float or bool.

    Raises
    ------
    ValueError
        If the string is not a valid Python literal.
    """
    return ast.literal_eval(string)


def combine_fragments(
    fragment1: Chem.Mol, fragment2: Chem.Mol, combinations: List[Tuple[int, int]]
) -> Optional[str]:
    """
    Combine two molecular fragments by overlapping the specified atoms.

    The overlapping atoms from ``fragment2`` are removed and their bonds are
    transferred to the corresponding atoms in ``fragment1``. The result is
    sanitised, standardised and returned as a canonical SMILES string.

    Parameters
    ----------
    fragment1 : Chem.Mol
        First molecular fragment, which receives the merged bonds.
    fragment2 : Chem.Mol
        Second molecular fragment, whose overlapping atoms are removed.
    combinations : list of tuple of int
        ``(atom1_idx, atom2_idx)`` pairs specifying which atoms to overlap
        between the two fragments.

    Returns
    -------
    str or None
        Canonical SMILES string of the combined molecule, or ``None`` if
        standardisation failed.
    """

    offset = fragment1.GetNumAtoms()

    f1_atoms = [fragment1.GetAtomWithIdx(atom1) for atom1, _ in combinations]
    f2_atoms = [fragment2.GetAtomWithIdx(atom2) for _, atom2 in combinations]
    bond_partners = [atom.GetNeighbors() for atom in f2_atoms]
    bond_orders = [[bond.GetBondType() for bond in atom.GetBonds()] for atom in f2_atoms]

    rw_mol = Chem.RWMol(Chem.CombineMols(fragment1, fragment2))
    Chem.RemoveAllHs(rw_mol)

    rw_mol.BeginBatchEdit()
    for atom1, atom2, partners, orders in zip(f1_atoms, f2_atoms, bond_partners, bond_orders):
        rw_mol.RemoveAtom(atom2.GetIdx() + offset)
        for partner, order in zip(partners, orders):
            rw_mol.AddBond(atom1.GetIdx(), partner.GetIdx() + offset, order)
    rw_mol.CommitBatchEdit()

    try:
        mol = safe_standardize_mol(rw_mol.GetMol(), add_hydrogens=True)
        return Chem.MolToSmiles(Chem.RemoveHs(mol))
    except Exception as e:
        print(f"Standardization failed: {e}", flush=True)
        return None


def valence_check(atom1: Tuple[str, int], atom2: Tuple[str, int]) -> bool:
    """
    Check whether two atoms can form a bond without violating valence rules.

    The available valence of both atoms is summed and compared against the
    default valence limit of ``atom1``.

    Parameters
    ----------
    atom1 : tuple of (str, int)
        Element symbol and currently used valence of the first atom.
    atom2 : tuple of (str, int)
        Element symbol and currently used valence of the second atom.

    Returns
    -------
    bool
        ``True`` if the atoms can bond without exceeding the valence limit of
        ``atom1``, ``False`` otherwise.
    """

    pt = Chem.rdchem.GetPeriodicTable()
    max_valence = pt.GetDefaultValence(atom1[0])
    valence1 = max_valence - atom1[1]
    valence2 = pt.GetDefaultValence(atom2[0]) - atom2[1]
    return valence1 + valence2 <= max_valence


def count_non_overlapping_sublists(lst: List[List[int]]) -> int:
    """
    Count the maximum number of non-overlapping intervals.

    Parameters
    ----------
    lst : list of list of int
        Intervals, each given as ``[start, end]``. The list is sorted in place
        by start position.

    Returns
    -------
    int
        Maximum number of non-overlapping intervals that can be selected.
    """
    lst.sort(key=lambda interval: interval[0])
    count = 1
    for previous, current in zip(lst, lst[1:]):
        if previous[1] <= current[0]:
            count += 1
    return count


def get_possible_combinations(
    idx_map1: Dict[int, List], idx_map2: Dict[int, List]
) -> Optional[List[List[int]]]:
    """
    Find the valid atom pairs for combining two molecular fragments.

    A pair is valid when both atoms are the same element and their valences are
    compatible for bonding, as determined by :func:`valence_check`.

    Parameters
    ----------
    idx_map1 : dict
        Atom index mapping for fragment1 {atom_idx: (element, valence_used)}.
    idx_map2 : dict
        Atom index mapping for fragment2 {atom_idx: (element, valence_used)}.

    Returns
    -------
    list or None
        Randomly shuffled list of valid [atom1_idx, atom2_idx] pairs,
        or None if no valid combinations exist.
    """

    possible_combinations = [
        [atom1, atom2]
        for atom1, properties1 in idx_map1.items()
        for atom2, properties2 in idx_map2.items()
        if properties1[0] == properties2[0] and valence_check(properties1, properties2)
    ]

    if possible_combinations:
        random.shuffle(possible_combinations)
        return possible_combinations
    return None


def get_allowed_pairs(
    combinations: List[List[int]], k: int, max_iterations: int = 1000
) -> List[List[int]]:
    """
    Sample up to ``k`` non-conflicting atom pairs for fragment combination.

    A pair is drawn at random from the available combinations and accepted only
    if neither of its atoms already appears in a previously accepted pair. This
    repeats until ``k`` pairs have been collected or ``max_iterations`` attempts
    have been made.

    Parameters
    ----------
    combinations : list of list of int
        ``[atom1_idx, atom2_idx]`` pairs representing valid atom combinations
        between the two fragments.
    k : int
        Maximum number of pairs to select.
    max_iterations : int, optional
        Maximum number of attempts before giving up. Default is 1000.

    Returns
    -------
    list of list of int
        The selected ``[atom1_idx, atom2_idx]`` pairs, in which no atom appears
        more than once. Fewer than ``k`` pairs may be returned if conflicts
        prevent further selection.
    """

    sampled_sublists = []
    counter = 0

    while len(sampled_sublists) < k and counter < max_iterations:
        sublist = random.choice(combinations)

        if all(sublist[0] != prev[0] and sublist[1] != prev[1] for prev in sampled_sublists):
            sampled_sublists.append(sublist)
        counter += 1

    return sampled_sublists


def select_max_overlaps(atoms1: int, atoms2: int) -> int:
    """
    Determine the maximum possible atom overlap between two fragments.

    The result is the smaller of the two atom counts, which is the theoretical
    maximum number of atoms that could be overlapped when combining the
    fragments.

    Parameters
    ----------
    atoms1 : int
        Number of atoms in the first fragment.
    atoms2 : int
        Number of atoms in the second fragment.

    Returns
    -------
    int
        Maximum possible number of overlaps, limited by the smaller fragment.
    """
    return min(atoms1, atoms2)


def get_atom_type_index_mapping(
    fragment: str,
) -> Tuple[Optional[Chem.Mol], Optional[Dict[int, List]]]:
    """
    Map each atom of a fragment to its element symbol and free valence.

    The SMILES string is converted into an RDKit molecule without sanitisation,
    and each atom index is associated with its element symbol and remaining free
    valence.

    Parameters
    ----------
    fragment : str
        SMILES string representing a molecular fragment.

    Returns
    -------
    mol : Chem.Mol or None
        The parsed RDKit molecule, or ``None`` if parsing failed.
    atom_mapping : dict or None
        Mapping from atom index to ``[element_symbol, free_valence]``, or
        ``None`` if parsing failed.
    """

    try:
        mol = Chem.RemoveHs(Chem.MolFromSmiles(fragment, sanitize=False), implicitOnly=False)
    except (TypeError, Chem.KekulizeException, Chem.AtomValenceException):
        return None, None

    if mol is None:
        return None, None

    pt = Chem.rdchem.GetPeriodicTable()
    atom_type_index_mapping = defaultdict(list)

    for atom in mol.GetAtoms():
        free_valence = pt.GetDefaultValence(atom.GetSymbol()) - atom.GetExplicitValence()
        atom_type_index_mapping[atom.GetIdx()] = [atom.GetSymbol(), free_valence]

    return mol, atom_type_index_mapping


class ParsePathwayLog:
    """
    Parsing and visualisation of molecular assembly pathway logs.

    Processes structured log files that document molecular assembly
    pathways, converting them into NetworkX directed graphs that represent
    the step-by-step construction of complex molecules from basic building
    blocks.

    Attributes
    ----------
    pathway_log : str
        Original pathway log content.
    atom_lines : list
        Parsed atomic data from graph section.
    building_block_lines : list
        Parsed building block data.
    steps_lines : dict
        Assembly step definitions.
    digraph_lines : list
        Graph connectivity data.
    G : networkx.MultiDiGraph
        Constructed molecular assembly graph.
    nodes_per_level : dict
        Count of nodes at each assembly level.
    """

    def __init__(self, pathway_log: str) -> None:
        """
        Initialize pathway parser and automatically process molecular assembly log.

        Creates a complete molecular assembly pathway analysis by parsing the structured
        log, building a directed graph representation, validating the assembly sequence,
        and computing hierarchical statistics. All processing occurs during initialization.

        Parameters
        ----------
        pathway_log : str
            Structured log content with required sections:
            - "#####Graph#####": Graph structure data
            - "#####Atoms#####": Atomic composition information
            - "#####Steps#####": Assembly step definitions
            - "#####Digraph#####": Directed graph connectivity
        """
        self.pathway_log = pathway_log
        self.atom_lines, self.building_block_lines, self.steps_lines, self.digraph_lines = (
            self._parse_log()
        )
        self.G = self._build_multidigraph()
        self._validate_graph()
        self._assign_levels()
        self.nodes_per_level = self._count_nodes_per_level()

    def _parse_log(self) -> Tuple[List, List, Dict, List]:
        """Parse graph atoms, building blocks, steps and connectivity from the log.

        Section headers select the destination, and Python literal values are
        decoded with :func:`destringyfy`. Return these four collections in the
        same order.
        """
        atom_lines, building_block_lines, steps_lines, digraph_lines = [], [], {}, []
        blocks = {
            "#####Graph#####": "atom",
            "#####Atoms#####": "building_block",
            "#####Steps#####": "steps",
            "#####Digraph#####": "digraph",
        }
        current_block = None

        for line in self.pathway_log.split("\n"):
            if line in blocks:
                current_block = blocks[line]
                continue
            if not line.strip():
                continue

            if current_block == "atom":
                atom_lines.append(destringyfy(line))
            elif current_block in ("building_block", "steps"):
                parts = line.split("=")
                name, value = parts[0], destringyfy(parts[-1])
                if current_block == "building_block":
                    building_block_lines.append([name, value])
                else:
                    steps_lines[name.replace("step", "")] = value
            elif current_block == "digraph":
                digraph_lines.append(destringyfy(line))

        return atom_lines, building_block_lines, steps_lines, digraph_lines

    def _build_multidigraph(self) -> nx.MultiDiGraph:
        """Build a fragment graph with two incoming edges per assembly step."""
        graph = nx.MultiDiGraph()
        smiles_graph = self._build_basic_building_blocks()
        graph.add_nodes_from(smiles_graph.values())

        for i in range(0, len(self.digraph_lines), 2):
            step_name = self.digraph_lines[i][-1]
            product = self._build_fragment_for_step(step_name.replace("step_", ""))
            smiles_graph[step_name] = product
            graph.add_node(product)
            graph.add_edge(smiles_graph[self.digraph_lines[i][0]], product)
            graph.add_edge(smiles_graph[self.digraph_lines[i + 1][0]], product)

        return graph

    def _build_basic_building_blocks(self) -> Dict[str, str]:
        """Map virtual object IDs to the SMILES of their two-atom building blocks."""
        building_blocks = {}
        for i, line in enumerate(self.building_block_lines):
            atoms, bond_type = line[1][0], line[1][-1]
            molecule = Chem.EditableMol(Chem.Mol())
            atom1 = molecule.AddAtom(Chem.Atom(atoms[0]))
            atom2 = molecule.AddAtom(Chem.Atom(atoms[-1]))
            molecule.AddBond(atom1, atom2, bond_types[bond_type])
            building_blocks[f"virtual_object_{i}"] = Chem.MolToSmiles(molecule.GetMol())
        return building_blocks

    def _build_fragment_for_step(self, step: str) -> str:
        """Build a step's fragment from its atom and bond data and return its SMILES."""

        bond_ids = self.steps_lines[step]
        atom_ids = list({atom for bond in bond_ids for atom in bond})
        atoms = [self.atom_lines[-2][atom_id] for atom_id in atom_ids]
        bonds = {
            tuple(bond): self.atom_lines[-1][self.atom_lines[1].index(bond)] for bond in bond_ids
        }

        molecule = Chem.EditableMol(Chem.Mol())
        id_mapping = {atom_id: i for i, atom_id in enumerate(atom_ids)}
        for atom in atoms:
            molecule.AddAtom(Chem.Atom(atom))
        for (atom1, atom2), bond_type in bonds.items():
            molecule.AddBond(id_mapping[atom1], id_mapping[atom2], bond_types[bond_type])
        return Chem.MolToSmiles(molecule.GetMol())

    def _validate_graph(self) -> None:
        """Raise ValueError if a fragment has more than two incoming edges."""
        for node, degree in self.G.in_degree:
            if degree > 2:
                raise ValueError("Node has more than 2 predecessors - invalid!")

    def _assign_levels(self) -> None:
        """Set building blocks to level 0 and assign the depth of each later step."""
        for node in self.G.nodes:
            if self.G.in_degree(node) == 0:
                self.G.nodes[node].update({"level": 0, "assembly_index": 1})
            else:
                self.G.nodes[node]["level"] = self._get_level(node)

    def _get_level(self, node: Any) -> int:
        """Return the depth derived from a node's incoming assembly edges."""

        predecessors = [source for source, _ in self.G.in_edges(node)]
        if not predecessors:
            return 0
        if len(predecessors) == 2:
            return max(self.G.nodes[pred]["level"] for pred in predecessors) + 1
        return self._get_level(predecessors[0])

    def _count_nodes_per_level(self) -> Dict[int, int]:
        """Count fragments at each assembly depth, preserving level encounter order."""
        levels = {}
        for _, attributes in self.G.nodes(data=True):
            level = attributes["level"]
            levels[level] = levels.get(level, 0) + 1
        return levels

    def _get_node_positions(self) -> Dict[Any, List[float]]:
        """Arrange nodes by assembly depth, preserving order within each level.

        Each level's x coordinate is twice its depth. Its y coordinates are
        evenly spaced from minus to plus the number of nodes in that level.
        """
        positions = {}
        sorted_nodes = sorted(self.G.nodes(data=True), key=lambda x: x[1]["level"])
        current_level, layer_positions = None, None

        for node, attributes in sorted_nodes:
            level = attributes["level"]
            if level != current_level:
                current_level = level
                count = self.nodes_per_level[level]
                layer_positions = iter(np.linspace(-count, count, count))
            positions[node] = [level * 2, next(layer_positions)]

        return positions

    def plot_layered_graph(self, show_molecules: bool = False, save_fig: bool = True) -> None:
        """
        Plot the assembly pathway as a layered graph.

        Nodes represent molecular fragments and edges show assembly
        relationships, arranged by assembly depth level, with optional molecular
        structure overlays.

        Parameters
        ----------
        show_molecules : bool, optional
            If True, overlay molecular structure images on the nodes. Default is
            False.
        save_fig : bool, optional
            If True, save the plot as an SVG file; if False, display the plot
            interactively. Default is True.

        Returns
        -------
        None
        """
        _, ax = plt.subplots(figsize=(12, 7))
        cmap = plt.get_cmap("Blues")
        node_colors = [cmap(0.4) for _ in self.G.nodes]
        positions = self._get_node_positions()

        nx.draw(
            self.G,
            pos=positions,
            ax=ax,
            with_labels=False,
            node_size=100,
            node_color=node_colors,
            connectionstyle="arc3,rad=0.05",
            edge_color="grey",
            width=1,
        )

        if show_molecules:
            for smiles, (x, y) in positions.items():
                image = Draw.MolToImage(Chem.MolFromSmiles(smiles), size=(150, 150))
                imagebox = OffsetImage(image, zoom=0.3)
                ax.add_artist(AnnotationBbox(imagebox, (x, y + 0.6), frameon=True))

        if save_fig:
            plt.savefig("data/images/pathway.svg", dpi=200)
        else:
            plt.show()


class Molecule:
    """
    Unified interface for molecular structure analysis and hierarchical assembly visualization.

    This class provides a comprehensive framework for molecular pathway analysis that can
    work with existing assembly pathway data or compute new pathways using external tools.
    Designed for lazy evaluation where pathway computation occurs only when needed.

    Attributes
    ----------
    smiles : str
        SMILES string representation of the molecule.
    pathway : list of str or None
        Pre-existing assembly pathway steps.
    assembly_index : int or None
        Position index in assembly sequence.
    G : networkx.DiGraph or None
        NetworkX directed graph representing assembly pathway.
    timeout : int
        Timeout in seconds for external pathway computation.
    pathway_log_string : str or None
        Raw pathway computation log.
    pathway_fragments : list or None
        Molecular fragments in pathway.
    pathwayLogObj : ParsePathwayLog or None
        Parsed pathway log object.
    assembly_output_path : str or None
        Path to pathway output files.
    """

    def __init__(
        self,
        smiles: str = "",
        pathway: Optional[list[str]] = None,
        assembly_index: Optional[int] = None,
        G: Optional[nx.DiGraph] = None,
        timeout: Optional[int] = 60,
    ) -> None:
        """
        Initialize Molecule object with flexible input options for pathway analysis.

        Creates a Molecule object that can work with various types of input:
        existing molecular structures, known pathways/assembly graphs. The object
        is designed for lazy evaluation - pathway computation and analysis occur
        only when needed.

        Parameters
        ----------
        smiles : str, optional
            SMILES string of target molecule. If empty, will be extracted
            from graph or computed from pathway, by default "".
        pathway : list of str, optional
            Pre-existing assembly pathway steps. Used when pathway is
            already known, by default None.
        assembly_index : int, optional
            Position index in assembly sequence. Used for tracking
            molecular position, by default None.
        G : networkx.DiGraph, optional
            NetworkX directed graph representing assembly pathway.
            If provided, SMILES extracted from final node, by default None.
        timeout : int, optional
            Timeout in seconds for external pathway computation
            tools, by default 60.
        """
        self.smiles = smiles
        self.pathway = pathway
        self.assembly_index = assembly_index
        self.G = G
        self.timeout = timeout
        self.pathway_log_string = None
        self.pathway_fragments = None
        self.pathwayLogObj = None
        self.assembly_output_path = None

        if G:
            self.smiles = list(G.nodes)[-1]

    def get_smiles(self) -> str:
        """Return the molecule's SMILES, computing its pathway and graph if needed."""
        if not self.smiles:
            self.reconstruct_pathway()
            self.construct_layered_graph()
        return self.smiles

    def calc_pathway(self) -> None:
        """
        Execute external molecular assembly tool to compute assembly pathway.

        Converts the molecule to MOL file format and runs the external assembly
        software to compute the assembly pathway, handling process execution,
        timeout management and file path tracking for subsequent analysis.

        Returns
        -------
        None

        Notes
        -----
        The SMILES string is written to a temporary MOL file, the external
        assembly tool is launched as a subprocess and interrupted if the
        computation exceeds ``self.timeout``, and the location of the pathway
        output file is stored on ``self.assembly_output_path``.
        """
        mol = Chem.MolFromSmiles(self.smiles)
        Chem.MolToMolFile(mol, 'temp.mol')
        mol_file_path = Path("temp.mol")
        output_base = mol_file_path.parent / mol_file_path.stem
        proc = subprocess.Popen(
            [add_assembly_to_path(), output_base],
            stdout=subprocess.DEVNULL,
        )
        try:
            proc.wait(timeout=self.timeout)
        except subprocess.TimeoutExpired:
            # SIGINT asks the calculator to save its best result. On Windows,
            # Popen cannot deliver it to an ordinary child process, so the only
            # option is to terminate; see _run_assembler in assembly.py.
            if os.name == "nt":
                proc.terminate()
            else:
                proc.send_signal(signal.SIGINT)

        self.assembly_output_path = f"{output_base}Pathway"

    def reconstruct_pathway(self) -> None:
        """
        Compute and parse molecular assembly pathway from external tools.

        Executes the complete pathway computation pipeline: it runs the external
        assembly software, parses the output files and extracts the pathway data
        for analysis, then removes all temporary files created in the process.

        Returns
        -------
        None

        Notes
        -----
        This method calls :meth:`calc_pathway` to run the external assembly
        tool, then sets ``self.pathway_fragments`` to the list of molecular
        fragments in the pathway and ``self.pathway_log_string`` to the raw
        pathway computation log. ``self.assembly_output_path`` is set by
        :meth:`calc_pathway`.
        """
        self.calc_pathway()
        _, self.pathway_fragments, self.pathway_log_string = parse_pathway_file(
            self.assembly_output_path, vo_type="inchi", log=True
        )
        for filename in ('temp.mol', 'tempOut', 'tempPathway'):
            os.remove(filename)

    def construct_layered_graph(self) -> None:
        """Parse the pathway log into a graph and take its last node as the SMILES."""
        self.pathwayLogObj = ParsePathwayLog(self.pathway_log_string)
        self.G = self.pathwayLogObj.G
        self.smiles = list(self.G.nodes)[-1]

    def plot_layered_graph(self, show_molecule: bool = True) -> None:
        """
        Create hierarchical visualization of the molecular assembly pathway.

        Delegates to the :class:`ParsePathwayLog` object to generate a layered
        graph plot showing the step-by-step assembly process.

        Parameters
        ----------
        show_molecule : bool, optional
            If True, display molecular structure images on the graph nodes.
            Default is True.

        Returns
        -------
        None
        """
        self.pathwayLogObj.plot_layered_graph(show_molecule)


class MoleculeSpace:
    """
    Analysis of a collection of molecular assembly pathways.

    This class provides analysis tools for collections of molecular
    pathways, enabling the study of shared assembly fragments, common
    building blocks and hierarchical relationships across multiple target
    molecules. It constructs unified graphs that reveal the interconnected
    nature of molecular assembly space and supports fragment pool analysis.

    Attributes
    ----------
    molecules : list of Molecule
        The retained molecules.
    molecule_smiles : list of str
        SMILES strings of the retained molecules.
    joined_smiles : str
        The molecule SMILES strings joined with ``"."``.
    joined_assembly_graph : nx.MultiDiGraph or None
        Unified assembly graph, populated by :meth:`construct_joined_graph`.
    root_nodes : list of str or None
        Building blocks of the unified graph.
    leaf_nodes : list of str or None
        Observed endpoint molecules of the unified graph.
    """

    def __init__(self, molecules: List['Molecule']) -> None:
        """
        Create a MoleculeSpace for analysing multiple pathways collectively.

        SMILES strings are extracted from all molecules, invalid entries are
        filtered out, and the data structures for subsequent graph construction
        and analysis are set up.

        Parameters
        ----------
        molecules : list of Molecule
            Molecules with computed or computable assembly pathways. Molecules
            returning a ``None`` SMILES string are filtered out automatically.
        """
        self.molecules = molecules
        self.molecule_smiles = [molecule.get_smiles() for molecule in molecules]
        self._remove_none()
        self.joined_smiles = ".".join(self.molecule_smiles)
        self.joined_assembly_graph = None
        self.joined_assembly_graph_minus_x = None
        self.max_assembly_index = None
        self.root_nodes = None
        self.leaf_nodes = None

    def _remove_none(self) -> None:
        """Remove molecules whose SMILES is None and refresh the retained SMILES."""
        self.molecules = [mol for mol in self.molecules if mol.get_smiles() is not None]
        self.molecule_smiles = [mol.get_smiles() for mol in self.molecules]

    def _set_root_nodes(self) -> None:
        """Record graph nodes with no incoming edges as the building blocks."""
        self.root_nodes = [
            node
            for node in self.joined_assembly_graph.nodes
            if self.joined_assembly_graph.in_degree(node) == 0
        ]

    def _set_leaf_nodes(self) -> None:
        """Record observed molecule SMILES that appear in the joined graph."""
        self.leaf_nodes = [
            node for node in self.molecule_smiles if node in self.joined_assembly_graph.nodes
        ]

    def construct_joined_graph(self) -> None:
        """Merge molecule pathways and identify the building blocks and targets."""
        self.joined_assembly_graph = compose_all([mol.G for mol in self.molecules])
        self._set_root_nodes()
        self._set_leaf_nodes()

    def a_minus_x_assembly_pool(
        self, X: int = 1, get_graph: bool = True, remove_paths: bool = False
    ) -> Tuple[Union[nx.MultiDiGraph, List[str]], int]:
        """
        Generate fragment pool by reducing assembly depth by X levels.

        Creates a simplified molecular fragment pool by removing the X most complex
        assembly levels, effectively "stepping back" in the assembly space to
        obtain simpler fragments.

        Parameters
        ----------
        X : int, optional
            Number of assembly levels to remove, reducing complexity. Default is
            1, which removes the final assembly step.
        get_graph : bool, optional
            If True, return the graph object; if False, return the list of
            nodes. Default is True.
        remove_paths : bool, optional
            If True, remove entire pathway fragments and decrement the usage
            counts. Default is False.

        Returns
        -------
        pool : nx.MultiDiGraph or list of str
            The simplified assembly graph, or its node list when ``get_graph``
            is False.
        removed_observed : int
            Number of observed target molecules removed.

        Raises
        ------
        ValueError
            If ``X`` exceeds the maximum assembly index of the joined graph.

        Notes
        -----
        The joined graph is constructed first if it does not already exist. The
        maximum complexity level is found, nodes above the resulting threshold
        are identified, entire pathway fragments are optionally removed with
        their usage counts updated, and the remaining nodes above the threshold
        are then removed.
        """
        if self.joined_assembly_graph is None:
            print("Constructing joined assembly graph.", flush=True)
            self.construct_joined_graph()

        self.max_assembly_index = max(
            self.joined_assembly_graph.nodes.data("level"), key=lambda x: x[-1]
        )[-1]

        if X > self.max_assembly_index:
            raise ValueError(
                f"X must be less than or equal to the maximum assembly index {self.max_assembly_index}"
            )

        max_level = self.max_assembly_index - X
        temp_graph = self.joined_assembly_graph.copy()
        to_remove = [
            node for node in self.leaf_nodes if temp_graph.nodes[node]["level"] > max_level
        ]

        removed_observed = 0
        if remove_paths:
            for node in to_remove:
                if not temp_graph.has_node(node):
                    print(f"Node {node} not in graph", flush=True)
                    continue
                try:
                    pw_nodes = self.molecules[self.molecule_smiles.index(node)].G.nodes
                except Exception as e:
                    print(f"Could not find {node}: {e}", flush=True)
                    temp_graph.remove_node(node)
                    continue

                for pw_node in pw_nodes:
                    if not temp_graph.has_node(pw_node):
                        continue
                    attributes = temp_graph.nodes[pw_node]
                    if attributes["count"] > 1:
                        attributes["count"] -= 1
                    else:
                        temp_graph.remove_node(pw_node)
                removed_observed += 1

        for node in list(temp_graph.nodes):
            if temp_graph.nodes[node]["level"] > max_level:
                temp_graph.remove_node(node)

        if not remove_paths:
            removed_observed += sum(1 for leaf in self.leaf_nodes if not temp_graph.has_node(leaf))

        self.joined_assembly_graph_minus_x = temp_graph
        pool = temp_graph if get_graph else list(temp_graph.nodes)
        return pool, removed_observed


class MoleculeGenerationAssemblyPool:
    """
    Generation of novel molecules from molecular fragment pools.

    See Pagel et al. [Pagel2024a]_ for details.

    This class implements a molecular generation algorithm that creates new
    molecules by randomly combining fragments from existing assembly
    pathways. It uses statistical sampling based on fragment occurrence
    frequencies and chemical compatibility to generate chemically reasonable
    novel molecular structures.

    Attributes
    ----------
    assembly_pool : MoleculeSpace
        Source of validated molecular fragments and pathway statistics.
    assembled_molecules : dict of {int: list}
        Generated molecules, keyed by the number of assembly steps taken.
    level_to_fragment : dict of {int: list of str} or None
        Fragments available at each assembly level, populated by
        :meth:`set_assembly_pool` and consumed during generation.
    bu_level_to_fragment : dict of {int: list of str} or None
        Pristine copy of ``level_to_fragment``, restored by
        :meth:`reset_level_to_fragment`.
    original_a_minus_X : nx.MultiDiGraph or None
        Copy of the reduced assembly graph taken by
        :meth:`set_assembly_pool`.
    diverged_assembly_graph : nx.MultiDiGraph or None
        Working graph that generated molecules are added to, populated by
        :meth:`construct_diverged_assembly_graph`.
    num_removed : int or None
        Number of nodes removed when the pool was reduced.
    layer_sampling_weights : dict of {int: float}
        Per-level sampling weights, populated by :meth:`set_sw_layer`.
    n_steps_sampling_weights : list of float
        Sampling weights indexed by step count, populated by
        :meth:`set_sw_n_steps`.

    References
    ----------

    .. [Pagel2024a] Pagel, S., Sharma, A., & Cronin, L. (2024).
           Mapping evolution of molecules across biochemistry with assembly
           theory. arXiv preprint arXiv:2409.05993.

    """

    def __init__(self, assembly_pool: 'MoleculeSpace') -> None:
        """
        Set up the molecular generation framework.

        Connects to a :class:`MoleculeSpace` object and initialises the data
        structures used for fragment-based molecule creation.

        Parameters
        ----------
        assembly_pool : MoleculeSpace
            Source of validated molecular fragments and assembly pathway
            statistics.
        """
        self.diverged_assembly_graph: Optional[nx.MultiDiGraph] = None
        self.original_a_minus_X = None
        self.bu_level_to_fragment = None
        self.level_to_fragment: Optional[dict[int, list[str]]] = None
        self.num_removed = None
        self.assembly_pool = assembly_pool
        self.assembled_molecules: dict[int, list] = defaultdict(list)

    def set_assembly_pool(self, x: int = 10, remove_pathways: bool = False) -> None:
        """
        Configure fragment pool for molecule generation by reducing steps in assembly depth.

        Extracts and organises molecular fragments from the assembly pool at a
        specified depth level, creating fragment libraries grouped by assembly
        depth. This establishes the foundation for subsequent weighted sampling
        and generation.

        Parameters
        ----------
        x : int, optional
            Assembly depth reduction level. Higher values create simpler
            fragment pools. Default is 10.
        remove_pathways : bool, optional
            If True, remove entire pathways and update the usage counts; if
            False, perform simple node removal. Default is False.

        Returns
        -------
        None

        Notes
        -----
        Fragments ``x`` levels below the maximum assembly depth are extracted
        and grouped by level, and only fragments with valid atomic information
        are included. Copies are stored on ``self.bu_level_to_fragment`` and
        ``self.original_a_minus_X`` so that the pool can be reset between
        generation attempts.
        """
        _, self.num_removed = self.assembly_pool.a_minus_x_assembly_pool(
            X=x, get_graph=False, remove_paths=remove_pathways
        )

        graph = self.assembly_pool.joined_assembly_graph_minus_x
        self.level_to_fragment = defaultdict(list)
        for node, level in nx.get_node_attributes(graph, "level").items():
            if graph.nodes[node].get("atomic_count") is not None:
                self.level_to_fragment[level].append(node)

        self.bu_level_to_fragment = self.level_to_fragment.copy()
        self.original_a_minus_X = deepcopy(graph)

    def reset_level_to_fragment(self) -> None:
        """
        Reset fragment pool to original state for independent molecule
        generation.

        Restores the level_to_fragment mapping from backup, ensuring each
        molecule generation process starts with the same initial fragment
        pool regardless of modifications made during previous generation
        attempts.

        Returns
        -------
        None
        """
        self.level_to_fragment = self.bu_level_to_fragment.copy()

    def get_leaf_nodes(self) -> List[Any]:
        """
        Identify 'observed' molecules in the diverged assembly graph.

        Returns all nodes with no outgoing edges, representing both the original
        observed molecules and the newly generated ones.

        Returns
        -------
        list
            Node IDs of all terminal molecules, that is those with an out-degree
            of zero.
        """
        return [node for node, degree in self.diverged_assembly_graph.out_degree() if degree == 0]

    def get_assembled_molecules(self) -> Optional[List[str]]:
        """
        Extract final products from all successful molecule generation attempts.

        Returns the terminal molecule from each generation process, that is the
        completed assembled structure after all assembly steps.

        Returns
        -------
        list of str or None
            The final assembled molecule SMILES strings, or ``None`` if no
            molecules have been generated.
        """
        if not self.assembled_molecules:
            return None
        return [molecules[-1][-1] for molecules in self.assembled_molecules.values() if molecules]

    def get_leaf_counts_per_level(self, min_level: int = 1) -> dict[int, int]:
        """
        Count target molecules (leaf nodes) at each assembly depth level.

        Creates a frequency distribution of final assembled molecules across
        assembly hierarchy levels, used for statistical weighting in generation
        algorithms to maintain realistic molecular complexity distributions.

        Parameters
        ----------
        min_level : int, optional
            Minimum assembly level to include in the counts. Default is 1, which
            excludes the building blocks.

        Returns
        -------
        dict
            Mapping from assembly level to the count of target molecules at that
            complexity level.
        """
        graph = self.assembly_pool.joined_assembly_graph
        leaf_counts = defaultdict(int)
        for node in self.assembly_pool.leaf_nodes:
            node_data = graph.nodes[node]
            if graph.out_degree(node) == 0 and node_data["level"] >= min_level:
                leaf_counts[node_data["level"]] += 1

        for level in range(min_level, self.assembly_pool.max_assembly_index + 1):
            leaf_counts.setdefault(level, 0)

        return leaf_counts

    def add_to_assembly_graph(self, parents: List[str], child: str) -> bool:
        """
        Integrate a newly generated molecule into the assembly depth graph.

        Adds a generated molecule to the extended assembly graph with the
        appropriate connectivity, hierarchy level and chemical metadata,
        establishing the molecule's position in the assembly network for future
        sampling.

        Parameters
        ----------
        parents : list of str
            SMILES strings of the two parent fragments that were combined.
        child : str
            SMILES string of the newly generated molecule.

        Returns
        -------
        bool
            True if the molecule was added to the graph, False if molecular
            processing failed.

        Notes
        -----
        The atomic composition and free valence are computed first, then the
        assembly relationships from each parent to the child are added, the
        hierarchical level is set to ``max(parent_levels) + 1``, the count,
        level and atomic information are attached, and the molecule is
        registered in the level-based fragment lists.
        """
        periodic_table = Chem.rdchem.GetPeriodicTable()
        try:
            atomic_count = {
                atom.GetAtomicNum()
                for atom in Chem.MolFromSmiles(child).GetAtoms()
                if periodic_table.GetDefaultValence(atom.GetSymbol()) > atom.GetExplicitValence()
            }
        except AttributeError:
            print(child, flush=True)
            return False

        graph = self.assembly_pool.joined_assembly_graph_minus_x
        for parent in parents:
            graph.add_edge(parent, child)

        child_level = max(graph.nodes[parents[0]]["level"], graph.nodes[parents[1]]["level"]) + 1
        self.level_to_fragment[child_level].append(child)
        graph.nodes[child].update(
            level=child_level,
            count=1,
            atomic_count=atomic_count,
        )
        return True

    def construct_diverged_assembly_graph(self) -> None:
        """
        Create snapshot of the extended assembly graph including generated molecules.

        Captures the current state of the assembly pathway graph that has been
        expanded with newly generated molecules, preserving the complete network
        for analysis and visualization of both original and generated pathways.

        Returns
        -------
        None

        Notes
        -----
        ``self.diverged_assembly_graph`` is set to a deep copy of the expanded
        assembly graph, containing the original fragments plus the generated
        molecules.
        """
        self.diverged_assembly_graph = deepcopy(self.assembly_pool.joined_assembly_graph_minus_x)

    def set_sw_layer(self, exponent: float = 2.0) -> None:
        """
        Calculate sampling weights for assembly depth layers.

        Computes probabilistic weights for each assembly depth level from the
        fragment occurrence frequencies, so that sampling can be biased toward
        more common or better-represented levels during molecule generation.

        Parameters
        ----------
        exponent : float, optional
            Power used for frequency weighting. Higher values increase the bias
            toward frequent fragments. Default is 2.0, giving quadratic
            weighting.

        Returns
        -------
        None

        Notes
        -----
        Fragment counts are raised to ``exponent`` and summed within each level,
        giving a weight per complexity layer. The result is stored on
        ``self.layer_sampling_weights`` as a mapping from assembly level to
        aggregate sampling weight.
        """
        self.layer_sampling_weights = defaultdict(int)
        for _, data in self.assembly_pool.joined_assembly_graph.nodes(data=True):
            self.layer_sampling_weights[data["level"]] += data["count"] ** exponent

    def set_sw_n_steps(self, level: int = 0, exponent: float = 1.0) -> None:
        """
        Calculate sampling weights for assembly step counts based on target molecule distribution.

        Computes probabilistic weights for different numbers of assembly steps
        from the distribution of target molecules across assembly depth levels,
        so that generated molecules have realistic assembly sequence lengths.

        Parameters
        ----------
        level : int, optional
            Minimum assembly depth level to consider. Default is 0.
        exponent : float, optional
            Power used for frequency weighting. Higher values bias toward
            assembly depth levels holding more targets. Default is 1.0, giving
            linear weighting.

        Returns
        -------
        None

        Notes
        -----
        The leaf molecule counts per complexity level are used as the base
        weights, gaps for missing levels are filled with zeros, and the counts
        are raised to ``exponent``. The result is stored on
        ``self.n_steps_sampling_weights`` as a list indexed by step count, where
        element ``i`` is the relative probability of taking ``i`` assembly steps.
        """
        leaf_counts = self.get_leaf_counts_per_level(min_level=level + 1)
        self.n_steps_sampling_weights = [
            leaf_counts[key] ** exponent if key in leaf_counts else 0
            for key in range(max(leaf_counts) + 1)
        ]

    def sample_layer(
        self,
        exponent: float = 2.0,
        curr_depth: int = 0,
        black_listed_layers: Optional[List[int]] = None,
    ) -> int:
        """
        Randomly select an assembly depth layer for fragment sampling.

        Sampling by layer keeps the generated molecule size distribution
        roughly the same as that of the assembly pool.

        Performs weighted random selection of an assembly depth layer,
        constrained by the current assembly depth and excluding problematic
        layers, so that realistic molecular size distributions are
        maintained.

        Parameters
        ----------
        exponent : float, optional
            Power used in the frequency weighting calculation. Default is
            2.0, giving a quadratic bias toward common layers.
        curr_depth : int, optional
            Current assembly depth, which is the maximum layer allowed.
            Default is 0, meaning only building blocks are available.
        black_listed_layers : list of int, optional
            Assembly levels to exclude from sampling. Default is None,
            meaning no exclusions.

        Returns
        -------
        int
            The selected assembly depth level to sample fragments from.

        Notes
        -----
        Only layers at or below ``curr_depth`` are considered, selection is
        biased toward layers with higher statistical weights, blacklisted
        layers are excluded, and the layer sampling weights are computed
        lazily on first use.
        """
        if black_listed_layers is None:
            black_listed_layers = []
        if not hasattr(self, "layer_sampling_weights"):
            self.set_sw_layer(exponent=exponent)

        layer_ids, layer_weights = [], []
        for layer, weight in self.layer_sampling_weights.items():
            if layer <= curr_depth and layer not in black_listed_layers:
                layer_ids.append(layer)
                layer_weights.append(weight)

        return random.choices(layer_ids, weights=layer_weights, k=1)[0]

    def wrs_from_layer(
        self,
        base_mol: str,
        inverse: bool = False,
        layer: int = 0,
        exponent: float = 1.0,
        blacklist: Optional[List[str]] = None,
    ) -> Tuple[Optional[str], int]:
        """
        Weighted random sampling (WRS) of chemically compatible fragments from an assembly depth layer.

        Selects a random fragment from the specified assembly layer that is
        theoretically compatible with the base molecule, weighting the sampling
        by fragment usage frequency and atomic bonding compatibility.

        Parameters
        ----------
        base_mol : str
            SMILES string of the base molecule to find a compatible fragment
            for.
        inverse : bool, optional
            If True, invert ``exponent`` to bias toward rare fragments. Default
            is False, which biases toward common fragments.
        layer : int, optional
            Assembly depth layer to sample from. Default is 0.
        exponent : float, optional
            Power used for frequency weighting. Default is 1.0.
        blacklist : list of str, optional
            Reserved for compatibility; currently does not exclude fragments.
            Default is None.

        Returns
        -------
        fragment : str or None
            SMILES string of the selected fragment, or ``None`` if no compatible
            fragment was found.
        n_compatible : int
            Number of compatible fragments in the layer, or 0 if none were
            found.

        Notes
        -----
        A fragment is compatible when it shares at least one atom type with free
        valence with the base molecule. The ``atomic_count`` sets stored on the
        graph nodes are intersected to check this, which ensures the selected
        fragment can actually bond to the base molecule.
        """
        if inverse:
            exponent = -exponent

        nodes = self.assembly_pool.joined_assembly_graph_minus_x.nodes
        layer_fragments = []
        fragment_weights = []
        for node in self.level_to_fragment[layer]:
            node_data = nodes[node]
            if node_data["atomic_count"] & nodes[base_mol]["atomic_count"]:
                layer_fragments.append(node)
                fragment_weights.append(node_data["count"] ** exponent)

        if not layer_fragments:
            return None, 0
        fragment = random.choices(layer_fragments, weights=fragment_weights, k=1)[0]
        return fragment, len(layer_fragments)

    def weighted_n_steps_sampler(self, n: int, min_level: int = 1) -> int:
        """
        Sample number of assembly steps using target molecule distribution.

        Randomly selects how many assembly steps to perform from the statistical
        distribution of target molecule complexities, so that generated
        molecules follow realistic assembly sequence lengths.

        Parameters
        ----------
        n : int
            Maximum number of assembly steps allowed.
        min_level : int, optional
            Minimum complexity level to start weighting from. Default is 1,
            which excludes the building blocks.

        Returns
        -------
        int
            Number of assembly steps to perform, between 1 and ``n``.
        """
        return random.choices(
            list(range(1, n + 1)),
            weights=self.n_steps_sampling_weights[min_level + 1 :],
            k=1,
        )[0]

    def get_random_fragment_with_level(self, node_level: int) -> str:
        """
        Randomly selects a fragment from a specific assembly depth level.

        Performs uniform random selection from all available fragments at the
        specified assembly depth level, without weighting or compatibility
        constraints.

        Parameters
        ----------
        node_level : int
            Assembly depth level to sample from.

        Returns
        -------
        str
            SMILES string of the randomly selected fragment.
        """
        return random.choice(self.level_to_fragment[node_level])

    def combine_fragments_layer(
        self, fragment1: str, fragment2: str, assemble_object: 'Assemble', layer: int = 1
    ) -> Optional[str]:
        """
        Combine two molecular fragments into a new molecule.

        Parses the SMILES strings, extracts the atomic information and delegates
        to the assembly object for bond formation, handling molecular
        preprocessing and error cases.

        Parameters
        ----------
        fragment1 : str
            SMILES string of the first fragment.
        fragment2 : str
            SMILES string of the second fragment.
        assemble_object : Assemble
            Assembly engine object providing the ``create_bond`` method.
        layer : int, optional
            Assembly layer, that is the complexity level. Default is 1.

        Returns
        -------
        str or None
            SMILES string of the combined molecule, or ``None`` if either
            fragment failed to parse or the combination was invalid.

        Notes
        -----
        The SMILES strings are converted to RDKit molecules and their atom type
        and valence information extracted. If both parsed successfully, bond
        formation is delegated to ``assemble_object``.
        """
        mol1, atomtype_index_mapping1 = get_atom_type_index_mapping(fragment1)
        mol2, atomtype_index_mapping2 = get_atom_type_index_mapping(fragment2)

        if mol1 is None or mol2 is None:
            return None

        return assemble_object.create_bond(
            mol1,
            mol2,
            atomtype_index_mapping1,
            atomtype_index_mapping2,
            layer=layer,
        )

    def random_construct_n_molecules(
        self,
        n: int,
        steps: int,
        x: int = 10,
        inverse: bool = False,
        exponent: float = 1.0,
        layer_exponent: float = 2.0,
        step_exponent: float = 1.0,
        remove_pathways: bool = False,
    ) -> None:
        """
        Generate N novel molecules through probabilistic fragment assembly.

        Creates new molecules by iteratively combining fragments drawn from
        existing assembly pathways, using statistical sampling to balance
        chemical realism against novelty.

        Parameters
        ----------
        n : int
            Target number of molecules to generate.
        steps : int
            Maximum number of assembly steps per molecule.
        x : int, optional
            Assembly complexity reduction level for the fragment pool. Higher
            values use simpler fragments. Default is 10.
        inverse : bool, optional
            If True, bias toward rare fragments for novelty; if False, bias
            toward common fragments. Default is False.
        exponent : float, optional
            Fragment frequency weighting power. Default is 1.0.
        layer_exponent : float, optional
            Layer sampling bias strength. Default is 2.0.
        step_exponent : float, optional
            Step count sampling bias strength. Default is 1.0.
        remove_pathways : bool, optional
            If True, exclude entire pathways from the pool. Default is False.

        Returns
        -------
        None
            The results are stored on ``self.assembled_molecules`` and
            ``self.diverged_assembly_graph``.

        Notes
        -----
        The fragment pool is first extracted at complexity level ``A - x`` and
        the layer and step sampling weights are computed. For each target
        molecule a starting fragment is selected from the highest complexity
        level, the assembly sequence length is drawn by weighted sampling, and
        fragments are combined over multiple steps with chemical validation and
        error recovery, tracking the construction history and updating the
        assembly graph. Finally the extended assembly network including the
        generated molecules is created.
        """

        assemble_object = Assemble()
        self.set_assembly_pool(x=x, remove_pathways=remove_pathways)

        level = max(nx.get_node_attributes(self.original_a_minus_X, "level").values())
        self.set_sw_n_steps(level=level, exponent=step_exponent)

        # Missing observed levels can change the available number of steps.
        if self.assembly_pool.max_assembly_index - level != steps:
            steps = self.assembly_pool.max_assembly_index - level
        if n is None:
            n = self.num_removed

        assembled_molecules = 0
        attempt = 0
        while assembled_molecules < n:
            fragment1 = self.get_random_fragment_with_level(node_level=level)
            n_steps = self.weighted_n_steps_sampler(steps, min_level=level)

            for step in range(n_steps):
                max_tries = 5_000
                num_fragments = 1
                blacklist = []
                current_depth = level + step

                while num_fragments >= 1:
                    max_tries -= 1
                    if max_tries <= 0:
                        try:
                            del self.assembled_molecules[attempt]
                            self.assembled_molecules[attempt] = []
                        except KeyError:
                            pass
                        break

                    layer = self.sample_layer(
                        exponent=layer_exponent,
                        curr_depth=current_depth,
                    )
                    fragment2, num_fragments = self.wrs_from_layer(
                        base_mol=fragment1,
                        inverse=inverse,
                        exponent=exponent,
                        blacklist=blacklist,
                        layer=layer,
                    )
                    if fragment2 is None:
                        break

                    molecule = self.combine_fragments_layer(
                        fragment1,
                        fragment2,
                        assemble_object,
                        layer=current_depth,
                    )
                    if molecule is None:
                        if num_fragments != 0:
                            blacklist.append(fragment2)
                        continue
                    if Chem.MolFromSmiles(molecule) is None:
                        continue

                    self.assembled_molecules[attempt].append([fragment1, fragment2, molecule])
                    self.add_to_assembly_graph([fragment1, fragment2], molecule)
                    fragment1 = molecule
                    break

            if self.assembled_molecules[attempt]:
                assembled_molecules += 1
            attempt += 1

            self.reset_level_to_fragment()
        self.construct_diverged_assembly_graph()


class Assemble:
    """
    Assembly of molecular fragments by atom overlap and bond formation.

    This class implements molecular assembly algorithms that combine two
    molecular fragments by overlapping atoms and forming new bonds. It uses
    probabilistic selection of overlap sites, chemical validation and retry
    mechanisms to generate chemically reasonable molecular products from
    fragment precursors.

    See Pagel et al. [Pagel2024b]_ for details.

    Attributes
    ----------
    BASE_WEIGHTS : list of float
        Empirical probabilities of a fragment pair connecting at 1, 2, 3 or
        4 overlapping atoms, taken from the reaction statistics in
        [Pagel2024b]_.

    References
    ----------

    .. [Pagel2024b] Pagel, S., Sharma, A., & Cronin, L. (2024).
           Mapping evolution of molecules across biochemistry with assembly
           theory. arXiv preprint arXiv:2409.05993.

    """

    # Empirical probabilities for 1, 2, 3, or 4 overlapping atoms.
    BASE_WEIGHTS = [0.908, 0.075, 0.0137, 0.003]

    def __init__(self) -> None:
        """
        Initialise the assembly engine.

        The engine holds no per-instance state; the empirical overlap
        probabilities are taken from the class attribute ``BASE_WEIGHTS``.
        """

    def select_n_overlaps(
        self,
        f1_atoms: int,
        f2_atoms: int,
        p_combinations_copy: List[List[int]],
        layer: Optional[int] = None,
    ) -> List[List[int]]:
        """
        Select atom overlap pairs for molecular assembly using empirical probability weights.

        Determines how many and which atom pairs to overlap when combining two
        molecular fragments, using statistical weights derived from the chemical
        reaction patterns established in Pagel et al. This balances chemical
        realism against structural constraints when selecting feasible overlaps.

        Parameters
        ----------
        f1_atoms : int
            Number of atoms in the first fragment.
        f2_atoms : int
            Number of atoms in the second fragment.
        p_combinations_copy : list of list of int
            Available atom pair combinations for overlapping.
        layer : int, optional
            Assembly complexity layer, used to select layer-specific weights.

        Returns
        -------
        list of list of int
            The selected atom pairs for overlapping, as
            ``[[atom1_idx, atom2_idx], ...]``.
        """
        max_overlap = select_max_overlaps(f1_atoms, f2_atoms)
        allowed_combinations = min(
            count_non_overlapping_sublists(p_combinations_copy),
            max_overlap,
        )
        if isinstance(self.BASE_WEIGHTS, dict):
            layer_weights = self.BASE_WEIGHTS.get(layer, self.BASE_WEIGHTS[20])
            weights = [
                weight
                for count, weight in sorted(layer_weights.items())
                if count <= allowed_combinations
            ]
        else:
            weights = self.BASE_WEIGHTS[:allowed_combinations]

        num_combinations = random.choices(range(1, len(weights) + 1), weights=weights, k=1)[0]
        return get_allowed_pairs(p_combinations_copy, k=num_combinations)

    def create_bond(
        self,
        fragment1: Chem.Mol,
        fragment2: Chem.Mol,
        atomtype_index_mapping1: Dict[int, List],
        atomtype_index_mapping2: Dict[int, List],
        layer: Optional[int] = None,
    ) -> Optional[str]:
        """
        Combine two molecular fragments through probabilistic atom overlap assembly.

        The main assembly engine, which attempts to create a new molecule by
        combining two fragments through atom overlap. It uses iterative sampling
        with empirical probability weights and repeated retries to find a
        successful chemical combination.

        Parameters
        ----------
        fragment1 : Chem.Mol
            First molecular fragment to combine.
        fragment2 : Chem.Mol
            Second molecular fragment to combine.
        atomtype_index_mapping1 : dict
            Mapping from atom index to ``[element, valence]`` for ``fragment1``.
        atomtype_index_mapping2 : dict
            Mapping from atom index to ``[element, valence]`` for ``fragment2``.
        layer : int, optional
            Assembly complexity layer, used to select layer-specific overlap
            probabilities.

        Returns
        -------
        str or None
            SMILES string of the assembled molecule, or ``None`` if every
            attempt failed.
        """
        possible_combinations = get_possible_combinations(
            atomtype_index_mapping1, atomtype_index_mapping2
        )
        if not possible_combinations:
            return None

        for _ in range(5000):
            first, second = deepcopy(fragment1), deepcopy(fragment2)
            combinations = self.select_n_overlaps(
                first.GetNumAtoms(),
                second.GetNumAtoms(),
                possible_combinations,
                layer=layer,
            )
            for pair in combinations:
                possible_combinations.remove(pair)

            smiles = combine_fragments(first, second, combinations)
            if smiles:
                return smiles
        return None
