    smarts[8] = '([CH:1]#[*:2].[CH3:3][*:4])>>[C:1](#[*:2])[*:4].[CH4:3]'  # 9

    # Intra-molecular nitrogen
    smarts[9] = '([NH:1]([*:2])[*:3].[NH2:4][*:5])>>[N:1]([*:2])([*:3])[*:5].[NH3:4]'  # 10
    smarts[10] = '([NH2:1][*:2].[NH2:3][*:4])>>[NH:1]([*:2])[*:4].[NH3:3]'  # 11
