    smarts[4] = '([CH:1](=[*:2])[*:3].[CH3:4][*:5])>>[C:1](=[*:2])([*:3])[*:5].[CH4:4]'  # 5
    smarts[5] = '([CH2:1]=[*:2].[CH2:3]([*:4])[*:5])>>[C:1](=[*:2])([*:4])[*:5].[CH4:3]'  # 6
    smarts[6] = '([CH2:1]=[*:2].[CH3:3][*:4])>>[CH:1](=[*:2])[*:4].[CH4:3]'  # 7
