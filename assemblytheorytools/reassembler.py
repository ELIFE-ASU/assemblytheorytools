def assemble_smarts() -> Tuple[List[List[str]], List[List[Optional[Any]]]]:
    """
    Assemble the SMARTS reaction patterns used for synthesis planning.

    Initialise the collection of SMARTS reaction patterns used for
    retrosynthetic analysis and automated synthesis planning. The patterns
    describe molecular transformations involving carbon, nitrogen and oxygen
    atoms with various hybridisation states.

    Returns
    -------
    smarts : list of list of str
        Three groups of SMARTS reaction patterns:

        - ``smarts[0]`` (14 patterns) -- basic intermolecular reactions:
          carbon sp3 (indices 0-3), carbon sp2 (indices 4-7), carbon sp
          (index 8), nitrogen (indices 9-12) and oxygen (index 13).
        - ``smarts[1]`` (512 patterns) -- complex cross-reactions, covering
          carbon-carbon combinations across hybridisations, carbon-nitrogen,
          carbon-oxygen and nitrogen-nitrogen combinations, and overlapping
          and bridged transformations.
        - ``smarts[2]`` (14 patterns) -- intramolecular versions of the basic
          reactions.
    rxn : list of list of None
        Placeholders matching the shape of ``smarts``, to be filled with
        compiled reaction objects by the caller.

    Notes
    -----
    Each SMARTS pattern has the form
    ``[reactant1].[reactant2]>>[product1].[product2]``, where reactants are
    molecular fragments that can undergo the transformation, products are the
    fragments resulting from bond formation or breaking, and the atom mapping
    (``:1``, ``:2`` and so on) preserves atom identity across the
    transformation.

    Examples
    --------
    >>> smarts, rxn = assemble_smarts()
    >>> basic_patterns = smarts[0]  # basic reaction patterns
    >>> complex_patterns = smarts[1]  # cross-reaction patterns
    >>> intramolecular_patterns = smarts[2]  # intramolecular patterns
    """
    smarts = [
        list(_BASIC_ASSEMBLY_SMARTS),
        list(_CROSS_ASSEMBLY_SMARTS),
        list(_INTRAMOLECULAR_ASSEMBLY_SMARTS),
    ]
    return smarts, [[None] * len(group) for group in smarts]


def _enumerate_assemble_products(
    rxns: List[Any], mol1: List[Union[Chem.Mol, str]], mol2: List[Union[Chem.Mol, str]]
) -> Optional[Chem.Mol]:
    """
    Enumerate products of a list of reactions over both fragment orderings.

    Every reaction in *rxns* is applied to both ``(mol1, mol2)`` and
    ``(mol2, mol1)``, and the unique resulting SMILES are collected.

    Parameters
    ----------
    rxns : list
        RDKit reaction objects to apply, as produced by
        ``AllChem.ReactionFromSmarts``.
    mol1 : list
        Single-element list wrapping the first fragment.
    mol2 : list
        Single-element list wrapping the second fragment.

    Returns
    -------
    rdkit.Chem.Mol or None
        A randomly selected product, or None if no reaction produced one.
    """
    products = set()
    for reaction in rxns:
        for fragments in ((mol1, mol2), (mol2, mol1)):
            for product in Enumerator.EnumerateReaction(
                reaction, fragments, uniqueProductsOnly=True
            ):
                products.add(Chem.MolToSmiles(product[0]))

    if not products:
        return None
    # Sort before sampling so the random seed determines the chosen product.
    result = sorted(products)
    smiles = result[random.randint(0, len(result) - 1)]
    return Chem.MolFromSmiles(smiles)


def assemble(
    molecule1: Union[Chem.Mol, str], molecule2: Union[Chem.Mol, str], sites: int
) -> Optional[Chem.Mol]:
    """
    Assemble two molecular fragments using SMARTS reaction patterns.

    This function combines two molecular fragments through chemical reactions based on
    the specified number of reaction sites. It uses predefined SMARTS reaction patterns
    to enumerate possible products and returns a randomly selected valid product.

    The algorithm proceeds as follows:

    1. Load the SMARTS reaction patterns using :func:`assemble_smarts`.
    2. Compile the patterns for the requested number of sites.
    3. For the specified number of sites, iterate through all relevant reaction
       patterns, test both permutations of the input molecules (``mol1 + mol2``
       and ``mol2 + mol1``), enumerate all possible products for each reaction,
       and collect the unique products as SMILES strings.
    4. Return a randomly selected product from the valid results.

    Parameters
    ----------
    molecule1 : rdkit.Chem.Mol or str
        First molecular fragment (RDKit Mol object or SMILES string).
    molecule2 : rdkit.Chem.Mol or str
        Second molecular fragment (RDKit Mol object or SMILES string).
    sites : int
        Number of reaction sites to consider:
        - 1: Uses basic intermolecular reactions (rxn[0])
        - 2: Uses complex cross-reactions (rxn[1])
        - >2: Not supported, returns None

    Returns
    -------
    rdkit.Chem.Mol or None
        RDKit Mol object of a randomly selected product if successful,
        None if no valid products are generated or sites > 2.

    Examples
    --------
    >>> from rdkit import Chem
    >>> import assemblytheorytools as att
    >>> product = att.assemble(Chem.MolFromSmiles("OCC(O)CO"),
    ...                        Chem.MolFromSmiles("C=C"), 1)
    >>> Chem.MolToSmiles(product)
    'C=C(O)C(O)CO'

    The product is chosen at random from the applicable templates, so seed
    :mod:`random` when a reproducible result is needed.
    """

    if sites not in (1, 2):
        return None

    smarts, _ = assemble_smarts()
    patterns = smarts[0 if sites == 1 else 1]
    reactions = [AllChem.ReactionFromSmarts(pattern) for pattern in patterns]
    return _enumerate_assemble_products(reactions, [molecule1], [molecule2])


def printer(mols: List[Chem.Mol]) -> None:
    """
    Generate and save grid images of molecular structures in batches.

    This function takes a list of RDKit molecule objects and creates visual grid
    representations, saving them as PNG files in the current working directory. Large collections are automatically
    split into manageable batches to prevent overcrowded images. Batch size is 50 molecules per image.

    Parameters
    ----------
    mols : list of rdkit.Chem.Mol
        List of RDKit Mol objects to be visualized. Each element
        should be a valid RDKit molecule object that can be rendered.

    Returns
    -------
    None
        Function saves images to disk but does not return any value.
    """

    for start in range(0, len(mols), 50):
        end = start + 50
        labels = [str(index) for index in range(start, min(end, len(mols)))]
        image = Draw.MolsToGridImage(mols[start:end], molsPerRow=10, legends=labels)
        image.save(f'Mols_{start}-{end}.png')


def filter_mol(mol: Union[Chem.Mol, List[Chem.Mol]]) -> Optional[Chem.Mol]:
    """
    Filter out molecules containing chemically unstable or undesirable substructures.

    This function screens input molecules against a predefined list of 51 problematic
    SMARTS patterns representing strained rings, unusual bonding patterns (e.g. cumulative double bonds), and
    chemically unstable motifs. Any molecule containing these substructures is
    rejected to ensure chemical validity and synthetic feasibility.

    Parameters
    ----------
    mol : rdkit.Chem.Mol or list of rdkit.Chem.Mol
        RDKit molecule object to be filtered. If a list is provided,
        one molecule is randomly selected for filtering.

    Returns
    -------
    rdkit.Chem.Mol or None
        Original molecule object if it passes all filters,
        None if any forbidden substructure is detected.
    """

    if type(mol) is list:
        # randomly select one molecule from the list
        mol = mol[random.randint(0, len(mol) - 1)]

    return (
        None if any(mol.HasSubstructMatch(pattern) for pattern in _EVIL_SUBSTRUCTURE_MOLS) else mol
    )


